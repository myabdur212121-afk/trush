#!/usr/bin/env bash
# Optional FULL Debian/Ubuntu TeX Live distribution, not just a large subset.
# Independent of both engines and font.sh; install an engine to get the fonts.
set -Eeuo pipefail
trap 'printf "[latex-full] Failed at line %s. Fix the error above and rerun.\n" "$LINENO" >&2' ERR

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
WORKSPACE="${MANIM_WORKSPACE:-$SCRIPT_DIR}"
DRY_RUN=0
for arg in "$@"; do
    case "$arg" in
        --dry-run) DRY_RUN=1 ;;
        -h|--help)
            cat <<'HELP'
Usage: bash latex_full.sh [--dry-run]
Install the actual texlive-full distribution, plus dvisvgm and real tipa.
WARNING: this downloads a lot of data, takes time and needs several GB of disk.
Does NOT install either Manim engine or download the two workspace fonts.

Supports ManimCE and ManimGL's full default TeX preamble, including dsfont,
calligra, physics and tipa, plus XeLaTeX and other TeX Live components.
Writes configs/manimgl-tex.yml (template: default); bin/manimgl uses it
unless you supply your own --config_file. Upgrades a prior slim setup.

MANIM_WORKSPACE: absolute shared workspace; default: this script's directory.
Run as your normal user with passwordless sudo on Debian/Ubuntu.
System TeX packages do not persist across Arena sandbox resets; rerun then.
HELP
            exit 0 ;;
        *) printf 'Unknown option: %s\n' "$arg" >&2; exit 2 ;;
    esac
done
[[ "$WORKSPACE" = /* ]] || { echo 'MANIM_WORKSPACE must be an absolute path.' >&2; exit 2; }
WORKSPACE="$(realpath -m -- "$WORKSPACE")"
PACKAGES=(texlive-full dvisvgm tipa)
if (( DRY_RUN )); then
    printf '[latex-full] Missing apt packages only: %s\n' "${PACKAGES[*]}"
    echo '[latex-full] WARNING: full TeX Live requires several GB and a large download.'
    echo '[latex-full] Verify the full ManimGL preamble and compile math to SVG.'
    printf '[latex-full] Write %s/configs/manimgl-tex.yml with template: default\n' "$WORKSPACE"
    echo '[latex-full] No engine install or workspace font download.'
    exit 0
fi
command -v apt-get >/dev/null 2>&1 || { echo 'This installer supports Debian/Ubuntu with apt-get.' >&2; exit 1; }
MISSING=()
for package in "${PACKAGES[@]}"; do
    if [[ "$(dpkg-query -W -f='${db:Status-Status}' "$package" 2>/dev/null || true)" != installed ]]; then MISSING+=("$package"); fi
done
if (( ${#MISSING[@]} )); then
    echo '[latex-full] Installing FULL TeX Live. Allow time and several GB of free disk space.'
    SUDO=()
    if (( EUID != 0 )); then
        if ! command -v sudo >/dev/null 2>&1 || ! sudo -n true; then
            echo 'Missing packages require root or passwordless sudo.' >&2
            exit 1
        fi
        SUDO=(sudo -n)
    fi
    "${SUDO[@]}" env DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=120 update
    "${SUDO[@]}" env DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=120 install -y --no-install-recommends "${MISSING[@]}"
fi
for package_file in standalone.cls babel.sty amsmath.sty amssymb.sty dsfont.sty setspace.sty tipa.sty relsize.sty textcomp.sty mathrsfs.sty calligra.sty wasysym.sty ragged2e.sty physics.sty xcolor.sty microtype.sty pifont.sty fontspec.sty; do
    kpsewhich "$package_file" >/dev/null || { printf 'Required TeX file missing: %s\n' "$package_file" >&2; exit 1; }
done

TMP_DIR="$(mktemp -d)"
trap 'rm -rf -- "$TMP_DIR"' EXIT
cat > "$TMP_DIR/check.tex" <<'TEX'
\documentclass[preview]{standalone}
\usepackage[english]{babel}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{amsmath,amssymb,dsfont,setspace,tipa,relsize,textcomp}
\usepackage{mathrsfs,calligra,wasysym,ragged2e,physics,xcolor,microtype,pifont}
\DisableLigatures{encoding = *, family = *}
\begin{document}
\( \mathds{1} + (a+b)^n = \mathds{1} + \sum_{k=0}^{n} \binom{n}{k}a^{n-k}b^k \)
\end{document}
TEX
if ! latex -interaction=nonstopmode -halt-on-error -output-directory="$TMP_DIR" "$TMP_DIR/check.tex" > "$TMP_DIR/latex.log" 2>&1; then
    tail -n 60 "$TMP_DIR/latex.log" >&2; exit 1
fi
if ! dvisvgm --no-fonts --output="$TMP_DIR/check.svg" "$TMP_DIR/check.dvi" > "$TMP_DIR/dvisvgm.log" 2>&1; then
    cat "$TMP_DIR/dvisvgm.log" >&2; exit 1
fi
[[ -s "$TMP_DIR/check.svg" ]] || { echo 'TeX-to-SVG verification produced no output.' >&2; exit 1; }

mkdir -p -- "$WORKSPACE/configs"
cat > "$WORKSPACE/configs/manimgl-tex.yml" <<'YAML'
# Generated by latex_full.sh. Full TeX Live supports the complete GL preamble.
# The bin/manimgl wrapper loads this unless an explicit --config_file is given.
tex:
  template: default
YAML
latex --version | sed -n '1p'
xelatex --version | sed -n '1p'
dvisvgm --version | sed -n '1p'
echo '[latex-full] Ready; full-preamble math-to-SVG check passed.'
echo '[latex-full] ManimGL wrapper uses template: default.'
