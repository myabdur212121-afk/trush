#!/usr/bin/env bash
# Optional, Manim-focused LaTeX + XeLaTeX. No texlive-full/fonts-extra bundle.
# Independent of both engines and font.sh; install an engine to get the fonts.
set -Eeuo pipefail
trap 'printf "[latex-slim] Failed at line %s. Fix the error above and rerun.\n" "$LINENO" >&2' ERR

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
WORKSPACE="${MANIM_WORKSPACE:-$SCRIPT_DIR}"
DRY_RUN=0
for arg in "$@"; do
    case "$arg" in
        --dry-run) DRY_RUN=1 ;;
        -h|--help)
            cat <<'HELP'
Usage: bash latex_slim.sh [--dry-run]
Install a smaller Manim-focused TeX distribution with latex, xelatex, dvisvgm,
standalone, common math/science packages, real tipa and core fonts.
It is smaller than full TeX Live, but is still a substantial system install.
Does NOT install either Manim engine, texlive-full or texlive-fonts-extra.

Supports ManimCE's default Tex/MathTex and ManimGL's basic TeX template.
Writes configs/manimgl-tex.yml (template: basic); the generated bin/manimgl
wrapper uses it automatically unless you supply your own --config_file.
Direct/activated ManimGL users should use Tex(..., template="basic").
Extended font packages such as dsfont/calligra require latex_full.sh.

MANIM_WORKSPACE: absolute shared workspace; default: this script's directory.
Run as your normal user with passwordless sudo on Debian/Ubuntu.
Running this after full LaTeX does not uninstall the larger packages.
HELP
            exit 0 ;;
        *) printf 'Unknown option: %s\n' "$arg" >&2; exit 2 ;;
    esac
done
[[ "$WORKSPACE" = /* ]] || { echo 'MANIM_WORKSPACE must be an absolute path.' >&2; exit 2; }
WORKSPACE="$(realpath -m -- "$WORKSPACE")"
PACKAGES=(
    texlive-latex-base texlive-latex-recommended texlive-latex-extra
    texlive-fonts-recommended texlive-science texlive-xetex
    dvisvgm tipa cm-super-minimal lmodern
)
if (( DRY_RUN )); then
    printf '[latex-slim] Missing apt packages only: %s\n' "${PACKAGES[*]}"
    echo '[latex-slim] Verify TeX packages and compile a math formula to SVG.'
    printf '[latex-slim] Write %s/configs/manimgl-tex.yml with template: basic\n' "$WORKSPACE"
    echo '[latex-slim] No engine install, no font download, no texlive-full/fonts-extra.'
    exit 0
fi
command -v apt-get >/dev/null 2>&1 || { echo 'This installer supports Debian/Ubuntu with apt-get.' >&2; exit 1; }
MISSING=()
for package in "${PACKAGES[@]}"; do
    if [[ "$(dpkg-query -W -f='${db:Status-Status}' "$package" 2>/dev/null || true)" != installed ]]; then MISSING+=("$package"); fi
done
if (( ${#MISSING[@]} )); then
    SUDO=()
    if (( EUID != 0 )); then
        if ! command -v sudo >/dev/null 2>&1 || ! sudo -n true; then
            echo 'Missing packages require root or passwordless sudo.' >&2
            exit 1
        fi
        SUDO=(sudo -n)
    fi
    "${SUDO[@]}" env DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=120 update
    "${SUDO[@]}" env DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=120 install -y --no-install-recommends "${MISSING[@]}"
fi
for package_file in standalone.cls babel.sty amsmath.sty amssymb.sty xcolor.sty physics.sty tipa.sty fontspec.sty; do
    kpsewhich "$package_file" >/dev/null || { printf 'Required TeX file missing: %s\n' "$package_file" >&2; exit 1; }
done

TMP_DIR="$(mktemp -d)"
trap 'rm -rf -- "$TMP_DIR"' EXIT
cat > "$TMP_DIR/check.tex" <<'TEX'
\documentclass[preview]{standalone}
\usepackage[english]{babel}
\usepackage{amsmath,amssymb,xcolor}
\begin{document}
\( (a+b)^n = \sum_{k=0}^{n} \binom{n}{k}a^{n-k}b^k \)
\end{document}
TEX
if ! latex -interaction=nonstopmode -halt-on-error -output-directory="$TMP_DIR" "$TMP_DIR/check.tex" > "$TMP_DIR/latex.log" 2>&1; then
    tail -n 60 "$TMP_DIR/latex.log" >&2; exit 1
fi
if ! dvisvgm --no-fonts --output="$TMP_DIR/check.svg" "$TMP_DIR/check.dvi" > "$TMP_DIR/dvisvgm.log" 2>&1; then
    cat "$TMP_DIR/dvisvgm.log" >&2; exit 1
fi
[[ -s "$TMP_DIR/check.svg" ]] || { echo 'TeX-to-SVG verification produced no output.' >&2; exit 1; }

mkdir -p -- "$WORKSPACE/configs"
cat > "$WORKSPACE/configs/manimgl-tex.yml" <<'YAML'
# Generated by latex_slim.sh. ManimGL's basic preamble avoids fonts-extra.
# The bin/manimgl wrapper loads this unless an explicit --config_file is given.
tex:
  template: basic
YAML
latex --version | sed -n '1p'
xelatex --version | sed -n '1p'
dvisvgm --version | sed -n '1p'
echo '[latex-slim] Ready; math-to-SVG check passed. ManimGL wrapper uses template: basic.'
echo '[latex-slim] For Bengali text, use Text(..., font="Noto Serif Bengali") or XeLaTeX.'
